"use client";

import { useEffect } from "react";
import { Controller, useFormContext, useWatch } from "react-hook-form";
import { InputText } from "primereact/inputtext";
import { InputTextarea } from "primereact/inputtextarea";
import { Button } from "primereact/button";
import { useGetGeneratedProductCode } from "@/hooks/API/products/useGetGeneratedProductCode";
import { HW3_RECORD_PREFIX } from "@/utils/constants";
import FormField from "./FormField";
import MoneyInput from "./MoneyInput";
import { FORM_LIMITS, FORM_MESSAGES, type FormMode, type ProductFormValues } from "./product-form.model";

// Step 1 — Basic info (design 8.1.1 #2–6 / 8.1.2 #1–5):
// product name, product code (create: from GET /products/generate-code, read-only + Regenerate;
// edit: read-only), unit price (list price), selling price (< unit price), detailed description.
export default function StepBasicInfo({ mode }: { mode: FormMode }) {
  const {
    register,
    control,
    trigger,
    getFieldState,
    resetField,
    setValue,
    formState: { errors },
  } = useFormContext<ProductFormValues>();
  const isCreate = mode === "create";

  // ---- Product code: generated by the server on create ----
  const codeQuery = useGetGeneratedProductCode(isCreate);
  const currentCode = useWatch({ control, name: "productCode" });
  useEffect(() => {
    // resetField = set the value AND make it the default, so a generated code alone never makes the form "dirty".
    // A newer code from the server also replaces an older one (e.g. the code inside a restored draft).
    if (isCreate && codeQuery.data && codeQuery.data !== currentCode) resetField("productCode", { defaultValue: codeQuery.data });
  }, [isCreate, codeQuery.data, currentCode, resetField]);

  const regenerateCode = async () => {
    const result = await codeQuery.refetch();
    if (result.data) setValue("productCode", result.data, { shouldDirty: true, shouldValidate: true });
  };

  // ---- Selling price is re-checked when the unit price changes (selling < unit) ----
  const price = useWatch({ control, name: "price" });
  useEffect(() => {
    const state = getFieldState("unitPrice");
    if (state.isTouched || state.invalid) void trigger("unitPrice");
  }, [price, getFieldState, trigger]);

  const codeHint = isCreate
    ? codeQuery.isFetching
      ? "상품코드를 생성하는 중…"
      : codeQuery.isError
        ? `상품코드를 생성하지 못했습니다: ${codeQuery.error.message}`
        : "상품코드는 상품 등록 시 자동 생성됩니다."
    : "상품코드는 변경할 수 없습니다.";

  return (
    <div className="product-form-grid">
      <FormField
        id="product-name"
        label="상품명"
        required
        error={errors.productName?.message}
        hint={isCreate ? `공용 QA 데이터입니다. 상품명은 반드시 ${HW3_RECORD_PREFIX} 접두어로 시작해 주세요.` : undefined}
      >
        {(field) => (
          <InputText
            {...field}
            placeholder="상품명"
            autoComplete="off"
            {...register("productName", {
              validate: (value) => {
                const trimmed = value.trim();
                if (!trimmed) return FORM_MESSAGES.productNameRequired;
                if (trimmed.length > FORM_LIMITS.productNameMax) return FORM_MESSAGES.productNameTooLong;
                return true;
              },
            })}
          />
        )}
      </FormField>

      <FormField id="product-code" label="상품코드" required={isCreate} error={errors.productCode?.message} hint={codeHint}>
        {(field) => (
          <div className="product-form-inline">
            <InputText
              {...field}
              readOnly
              placeholder={isCreate && codeQuery.isFetching ? "생성 중…" : "상품코드"}
              {...register("productCode", {
                validate: (value) => !isCreate || value.trim().length > 0 || FORM_MESSAGES.productCodeMissing,
              })}
            />
            {isCreate && (
              <Button
                type="button"
                label="다시 생성"
                icon="pi pi-refresh"
                outlined
                loading={codeQuery.isFetching}
                onClick={regenerateCode}
              />
            )}
          </div>
        )}
      </FormField>

      <Controller
        control={control}
        name="price"
        rules={{
          validate: (value) => {
            if (value === null) return FORM_MESSAGES.priceRequired;
            if (value <= 0) return FORM_MESSAGES.pricePositive;
            if (value > FORM_LIMITS.intMax) return FORM_MESSAGES.moneyTooLarge;
            return true;
          },
        }}
        render={({ field, fieldState }) => (
          <FormField id="product-price" label="단가" required error={fieldState.error?.message} hint="할인 전 정가입니다.">
            {(a11y) => (
              <MoneyInput {...a11y} ref={field.ref} name={field.name} value={field.value} onChange={field.onChange} onBlur={field.onBlur} placeholder="₩0" />
            )}
          </FormField>
        )}
      />

      <Controller
        control={control}
        name="unitPrice"
        rules={{
          validate: (value, values) => {
            if (value === null) return FORM_MESSAGES.unitPriceRequired;
            if (value <= 0) return FORM_MESSAGES.unitPricePositive;
            if (value > FORM_LIMITS.intMax) return FORM_MESSAGES.moneyTooLarge;
            if (values.price !== null && value >= values.price) return FORM_MESSAGES.unitPriceNotLower;
            return true;
          },
        }}
        render={({ field, fieldState }) => (
          <FormField
            id="product-unit-price"
            label="판매가"
            required
            error={fieldState.error?.message}
            hint="고객이 결제하는 실제 판매가입니다. 단가보다 낮아야 합니다."
          >
            {(a11y) => (
              <MoneyInput {...a11y} ref={field.ref} name={field.name} value={field.value} onChange={field.onChange} onBlur={field.onBlur} placeholder="₩0" />
            )}
          </FormField>
        )}
      />

      <FormField id="product-description" label="상세설명" required error={errors.description?.message} className="product-form-field-wide">
        {(field) => (
          <InputTextarea
            {...field}
            rows={6}
            autoResize={false}
            placeholder="상품 상세설명을 입력해 주세요."
            {...register("description", {
              validate: (value) => value.trim().length > 0 || FORM_MESSAGES.descriptionRequired,
            })}
          />
        )}
      </FormField>
    </div>
  );
}
